// Turns public/podpis-katka-tahy.svg (Illustrator export, groups tah-01,
// tah-02, ... in writing order; each = filled letter pieces + one pen
// polyline) into components/marketing/signature-strokes.ts.
// Run: npx tsx scripts/generate-signature-strokes.ts && npm run format
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "public/podpis-katka-tahy.svg";
const TARGET = "components/marketing/signature-strokes.ts";

const svg = readFileSync(SOURCE, "utf8");

// Illustrator puts stroke widths into <style> classes (.cls-3 { ... }).
const strokeWidthByClass = new Map<string, number>();
for (const [, selectors, body] of svg.matchAll(
    /((?:\.cls-\d+,?\s*)+)\{([^}]*)\}/g
)) {
    const width = body.match(/stroke-width:\s*([\d.]+)/)?.[1];
    if (!width) continue;
    for (const cls of selectors.match(/cls-\d+/g) ?? []) {
        strokeWidthByClass.set(cls, Number(width));
    }
}

const strokes = [...svg.matchAll(/<g id="tah-\d+">([\s\S]*?)<\/g>/g)].map(
    ([, group]) => {
        const fills = [...group.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(
            (match) => match[1]
        );
        const polyline = group.match(/<polyline[^>]*>/)?.[0] ?? "";
        const penPoints = polyline.match(/points="([^"]+)"/)?.[1].trim();
        const cls = polyline.match(/class="(cls-\d+)"/)?.[1];
        if (!penPoints || !cls) throw new Error("Tah bez čáry: " + group);

        const coords = penPoints.split(/\s+/).map(Number);
        let penLength = 0;
        for (let i = 2; i < coords.length; i += 2) {
            penLength += Math.hypot(
                coords[i] - coords[i - 2],
                coords[i + 1] - coords[i - 1]
            );
        }

        return {
            fills,
            penPoints,
            penWidth: strokeWidthByClass.get(cls),
            penLength: Math.round(penLength * 10) / 10,
        };
    }
);

const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];

writeFileSync(
    TARGET,
    `// Generated by scripts/generate-signature-strokes.ts from ${SOURCE} -
// each stroke = the filled letter pieces it draws + the pen line that
// uncovers them. Don't edit by hand.
export const SIGNATURE_VIEWBOX = ${JSON.stringify(viewBox)};

export const SIGNATURE_STROKES = ${JSON.stringify(strokes, null, 4)};
`
);
console.log(`${strokes.length} tahů -> ${TARGET}`);
